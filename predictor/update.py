#!/usr/bin/env python3
"""Refresh the offline snapshot (data.js) used by index.html when live ESPN
fetches are unavailable. Usage:  python3 update.py
Only fetches public ESPN JSON (no API key). Writes data.js next to this file."""
import json, os, sys, urllib.request, gzip, datetime

LEAGUES = ["eng.1", "esp.1", "ita.1", "ger.1", "fra.1", "usa.1", "uefa.champions"]
SB = "https://site.api.espn.com/apis/site/v2/sports/soccer/{l}/scoreboard?dates={y}&limit=1000"
ST = "https://site.api.espn.com/apis/v2/sports/soccer/{l}/standings"
HERE = os.path.dirname(os.path.abspath(__file__))

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0", "Accept-Encoding": "gzip"})
    with urllib.request.urlopen(req, timeout=30) as r:
        data = r.read()
        if r.headers.get("Content-Encoding") == "gzip":
            data = gzip.decompress(data)
    return json.loads(data)

def trim_event(e):
    c = e["competitions"][0]
    return {
        "id": e["id"], "date": e["date"], "name": e.get("name"),
        "season": {"year": e.get("season", {}).get("year")},
        "status": {"type": {k: e["status"]["type"].get(k) for k in ("state", "completed", "name")}},
        "competitions": [{
            "neutralSite": c.get("neutralSite"),
            "venue": {"fullName": (c.get("venue") or {}).get("fullName")},
            "competitors": [{
                "homeAway": t["homeAway"],
                "score": t.get("score"),
                "team": {k: t["team"].get(k) for k in ("id", "displayName", "shortDisplayName", "abbreviation", "logo")},
            } for t in c["competitors"]],
        }],
    }

def trim_standings(s):
    out = {"children": []}
    for ch in s.get("children", []):
        out["children"].append({"name": ch.get("name"), "standings": {"entries": [
            {"team": {"id": en["team"]["id"]},
             "stats": [{"name": st.get("name"), "value": st.get("value"), "displayValue": st.get("displayValue")}
                       for st in en.get("stats", []) if st.get("name") in ("rank", "points", "gamesPlayed")]}
            for en in ch["standings"]["entries"]]}})
    return out

def main():
    now = datetime.datetime.now(datetime.timezone.utc)
    end = now + datetime.timedelta(days=8)
    snap = {"fetchedAt": now.isoformat().replace("+00:00", "Z"), "leagues": {}}
    for l in LEAGUES:
        try:
            years = [now.year] + ([end.year] if end.year != now.year else [])
            first = get(SB.format(l=l, y=now.year))
            season_year = first["leagues"][0]["season"]["year"]
            league_name = first["leagues"][0].get("name", l)
            events = list(first.get("events", []))
            if season_year < now.year:
                events += get(SB.format(l=l, y=now.year - 1)).get("events", [])
            for y in years[1:]:
                events += get(SB.format(l=l, y=y)).get("events", [])
            # keep current-season results + upcoming fixtures only
            keep = [trim_event(e) for e in events
                    if e.get("season", {}).get("year") == season_year or e["status"]["type"].get("state") != "post"]
            try:
                st = trim_standings(get(ST.format(l=l)))
            except Exception as ex:
                print(f"  standings failed for {l}: {ex}", file=sys.stderr); st = {"children": []}
            snap["leagues"][l] = {"name": league_name, "seasonYear": season_year, "events": keep, "standings": st}
            print(f"{l}: {len(keep)} events (season {season_year})")
        except Exception as ex:
            print(f"FAILED {l}: {ex}", file=sys.stderr)
    with open(os.path.join(HERE, "data.js"), "w") as f:
        f.write("// Auto-generated by update.py - offline snapshot of public ESPN data\n")
        f.write("window.SNAPSHOT = " + json.dumps(snap, separators=(",", ":")) + ";\n")
    print("wrote data.js", snap["fetchedAt"])

if __name__ == "__main__":
    main()
